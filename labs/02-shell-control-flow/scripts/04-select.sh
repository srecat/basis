#!/bin/bash
echo "[SELECT] Выводим меню на экран:"
PS3="Выберите действие (1-3): "

# Эмулируем выбор цифры 2, чтобы скрипт не ждал ввода в автотестах
echo "2" | {
    select OPTION in "Запустить" "Остановить" "Выход"; do
        case $OPTION in
            "Запустить")
                echo "    Выбрано: Запуск"
                break
                ;;
            "Остановить")
                echo "    Выбрано: Остановка"
                break
                ;;
            "Выход")
                echo "    Выбрано: Выход"
                break
                ;;
            *)
                echo "    Ошибка: неверный выбор"
                ;;
        esac
    done
}
